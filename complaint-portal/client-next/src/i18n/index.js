export const URGENT_CATEGORY = "Urgent safety concern";

export function categoryLabel(lang, value) {
  if (value === URGENT_CATEGORY) return t(lang, "urgentTitle");
  const meta = CATEGORY_META.find((category) => category.value === value);
  return meta ? t(lang, meta.key) : value;
}
